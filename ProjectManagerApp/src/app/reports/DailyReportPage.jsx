const dayTitle = (day, lang) => `${weekdayLabel(day, lang)} ${formatDay(day)}`;

/**
 * One day of the report: figures, the site diary (weather, manpower,
 * equipment), work done (from orders), expenses, visitors and issues,
 * site notes.
 */
function DayBlock({ day, heading, notes, diaryEntry, onDeleteNote }) {
  const { t, lang } = useI18n();
  const { orders, engineResult, registries } = useProject();
  const r = useMemo(() => dayReport(orders, engineResult.tasks, day), [orders, engineResult.tasks, day]);
  const who = (o) => {
    const label = resolveWhoLabel(o.who, registries);
    return label === '—' ? '' : label;
  };

  return (
    <div className={s.day}>
      {heading && <h3 className={s.dayTitle}>{dayTitle(day, lang)}</h3>}

      {r.isEmpty ? (
        <p className={s.muted}>
          {t('reports.dayOrdersEmpty')}{' '}
          <Link to="/record" className="ui-no-print">
            {t('reports.goRecord')}
          </Link>
        </p>
      ) : (
        <dl className={s.figures}>
          <div className={s.figure}>
            <dt>{t('reports.orderCount')}</dt>
            <dd>{r.count}</dd>
          </div>
          <div className={s.figure}>
            <dt>{t('reports.workValue')}</dt>
            <dd>{compactCurrency(r.value, lang)}</dd>
          </div>
          <div className={s.figure}>
            <dt>{t('reports.totalExpenses')}</dt>
            <dd>{compactCurrency(r.expenseTotal, lang)}</dd>
          </div>
          {r.pending > 0 && (
            <div className={s.figure}>
              <dt>{t('common.pending')}</dt>
              <dd className={s.toneWarning}>{r.pending}</dd>
            </div>
          )}
        </dl>
      )}

      <DiaryConditions entry={diaryEntry} showEmpty={!heading} />

      {r.groups.length > 0 && (
        <SheetSection title={t('reports.workDone')} aside={<span className={s.tag}>{t('reports.autoGenerated')}</span>}>
          <div className={s.tableWrap}>
            <table className={s.table}>
              <thead>
                <tr>
                  <th>{t('gantt.colItem')}</th>
                  <th>{t('reports.colExecutedBy')}</th>
                  <th className={s.num}>{t('common.quantity')}</th>
                  <th className={s.num}>{t('reports.workValue')}</th>
                </tr>
              </thead>
              {r.groups.map((g) => (
                <tbody key={g.key}>
                  <tr className={s.groupRow}>
                    <td colSpan={2}>
                      {g.wbs && <span className={cx(s.wbs, 'ui-ltr')}>{g.wbs}</span>}
                      {g.name || t('reports.workWithoutTask')}
                    </td>
                    <td className={s.num}>
                      {formatNumber(g.qty)} {g.unit}
                    </td>
                    <td className={s.num}>{g.value > 0 ? compactCurrency(g.value, lang) : '—'}</td>
                  </tr>
                  {g.orders.map((o) => (
                    <tr key={o.id}>
                      <td>{typeLabel(o.type)}</td>
                      <td>
                        {who(o) || '—'}
                        {o.status !== 'approved' && <span className={s.pending}>{t('common.pending')}</span>}
                      </td>
                      <td className={s.num}>
                        {formatNumber(o.quantity)} {o.unit || g.unit}
                      </td>
                      <td />
                    </tr>
                  ))}
                </tbody>
              ))}
            </table>
          </div>
        </SheetSection>
      )}

      {r.expenses.length > 0 && (
        <SheetSection title={t('reports.recordedExpenses')}>
          <div className={s.tableWrap}>
            <table className={s.table}>
              <thead>
                <tr>
                  <th>{t('common.type')}</th>
                  <th>{t('reports.colParty')}</th>
                  <th className={s.num}>{t('reports.colAmountIqd')}</th>
                </tr>
              </thead>
              <tbody>
                {r.expenses.map((o) => (
                  <tr key={o.id}>
                    <td>{typeLabel(o.type)}</td>
                    <td>
                      {who(o) || '—'}
                      {o.status !== 'approved' && <span className={s.pending}>{t('common.pending')}</span>}
                    </td>
                    <td className={s.num}>{formatNumber(o.amount)}</td>
                  </tr>
                ))}
              </tbody>
              <tfoot>
                <tr>
                  <td colSpan={2}>{t('reports.totalExpenses')}</td>
                  <td className={s.num}>{formatNumber(r.expenseTotal)}</td>
                </tr>
              </tfoot>
            </table>
          </div>
        </SheetSection>
      )}

      <DiaryRemarks entry={diaryEntry} />

      {/* Day photos slot — the day's order photos (screen and print) go here,
          between the diary and the site notes (roadmap WS8, dayReport.photoIds). */}

      <SheetSection title={t('reports.siteNotes')}>
        {notes.length === 0 ? (
          <p className={s.muted}>{t('reports.noNotes')}</p>
        ) : (
          <ul className={s.notes}>
            {notes.map((n) => (
              <li key={n.id} className={s.note}>
                <div className={s.noteBody}>
                  <span className={s.noteMeta}>
                    {[n.engineer, n.taskWbs || n.taskName ? `${n.taskWbs} ${n.taskName}`.trim() : null].filter(Boolean).join(' · ')}
                  </span>
                  {n.details && <span className={s.noteText}>{n.details}</span>}
                  {Number(n.quantity) > 0 && <span className={s.noteMeta}>{t('reports.legacyQty', { qty: formatNumber(n.quantity) })}</span>}
                </div>
                <IconButton icon={Trash2} label={t('reports.deleteNote')} variant="ghost" size="sm" className="ui-no-print" onClick={() => onDeleteNote(n)} />
              </li>
            ))}
          </ul>
        )}
      </SheetSection>
    </div>
  );
}

/** The add-a-note form (screen only). */
function NoteForm({ day, engineers, onSave }) {
  const { t } = useI18n();
  const { tasks, orders, identity } = useProject();
  const [engineer, setEngineer] = useState(identity?.name || '');
  const [taskId, setTaskId] = useState('');
  const [details, setDetails] = useState('');
  const [tried, setTried] = useState(false);
  const missing = !engineer.trim() || !details.trim();

  const submit = (e) => {
    e.preventDefault();
    setTried(true);
    if (missing) return;
    onSave(createDailyNote({ date: day, engineer, task: tasks.find((x) => x.id === taskId) || null, details }));
    setTaskId('');
    setDetails('');
    setTried(false);
  };

  return (
    <Card title={t('reports.addNote')} subtitle={formatDay(day)} titleAs="h2" className="ui-no-print">
      <form className={s.form} onSubmit={submit}>
        <Field label={t('reports.engineerName')} error={tried && !engineer.trim() ? t('record.required') : undefined}>
          <Input value={engineer} list="pm-engineers" onChange={(e) => setEngineer(e.target.value)} />
        </Field>
        <datalist id="pm-engineers">
          {engineers.map((x) => (
            <option key={x} value={x} />
          ))}
        </datalist>
        <Field label={t('gantt.colItem')} optional>
          <TaskPicker tasks={tasks} orders={orders} value={taskId} onChange={setTaskId} optional />
        </Field>
        <Field label={t('reports.detailsNotes')} hint={t('reports.detailsPlaceholder')} error={tried && !details.trim() ? t('record.required') : undefined}>
          <Textarea rows={4} value={details} onChange={(e) => setDetails(e.target.value)} />
        </Field>
        <Button type="submit" variant="primary">
          {t('reports.saveNote')}
        </Button>
      </form>
    </Card>
  );
}

/**
 * /reports/daily — the day on site: work done and expenses built from the
 * day's orders, plus the engineer's site notes; one day or a whole period,
 * printable.
 */
export default function DailyReportPage() {
  const { t, lang } = useI18n();
  const toast = useToast();
  const { orders } = useProject();
  const allowed = useCan();
  const today = todayStr();
  const [notes, setNotes] = useState(loadDailyNotes);
  const [diary, setDiary] = useState(loadSiteDiary);
  const [mode, setMode] = useState('day');
  const [day, setDay] = useState(today);
  const [from, setFrom] = useState(() => addDays(today, -6));
  const [to, setTo] = useState(today);
  const [engineer, setEngineer] = useState('');
  const [toDelete, setToDelete] = useState(null);
  const [stamp, setStamp] = useState(() => issueStamp());

  useEffect(() => {
    saveDailyNotes(notes);
  }, [notes]);

  // The diary is saved on each edit (below); re-read it when it changes elsewhere (sync).
  useEffect(() => onStoreChange((key) => key === SITE_DIARY_STORAGE_KEY && setDiary(loadSiteDiary())), []);

  const saveDiaryDay = (entry) => {
    const next = putDiaryDay(diary, day, entry);
    saveSiteDiary(next);
    setDiary(next);
    toast({ title: t(isDiaryDayEmpty(entry) ? 'diary.cleared' : 'diary.saved') });
  };

  const engineers = useMemo(() => engineersOf(notes), [notes]);
  const notesFor = (d) => filterNotes(notes, { from: d, to: d, engineer: mode === 'range' ? engineer : '' });
  // A period prints the days with orders, notes or a diary (diary days only when no engineer is picked).
  const days =
    mode === 'day'
      ? [day]
      : [...new Set([...reportDays(orders, filterNotes(notes, { engineer }), from, to), ...(engineer ? [] : diaryDaysInRange(diary, from, to))])]
          .sort()
          .reverse();

  const print = () => {
    setStamp(issueStamp());
    setTimeout(() => window.print(), 50);
  };

  const period =
    mode === 'day'
      ? dayTitle(day, lang)
      : `${formatDay(from)} – ${formatDay(to)}${engineer ? ` · ${engineer}` : ''}`;

  return (
    <Page area="reports">
      <div className={cx(s.toolbar, 'ui-no-print')}>
        <Segmented
          label={t('reports.view')}
          value={mode}
          onChange={setMode}
          options={[
            { value: 'day', label: t('reports.modeDay') },
            { value: 'range', label: t('reports.modeRange') },
          ]}
        />
        {mode === 'day' ? (
          <div className={s.period}>
            <IconButton icon={ChevronLeft} label={t('planning.prevDay')} variant="secondary" className="ui-flip-rtl" onClick={() => setDay(addDays(day, -1))} />
            <Input type="date" aria-label={t('common.date')} className={s.dateInput} value={day} max={today} onChange={(e) => e.target.value && setDay(e.target.value)} />
            <IconButton icon={ChevronRight} label={t('planning.nextDay')} variant="secondary" className="ui-flip-rtl" disabled={day >= today} onClick={() => setDay(addDays(day, 1))} />
            {day !== today && (
              <Button size="sm" onClick={() => setDay(today)}>
                {t('common.today')}
              </Button>
            )}
          </div>
        ) : (
          <div className={s.group}>
            <Input type="date" aria-label={t('reports.fromDate')} className={s.dateInput} value={from} onChange={(e) => e.target.value && setFrom(e.target.value)} />
            <span aria-hidden="true">–</span>
            <Input type="date" aria-label={t('reports.toDate')} className={s.dateInput} value={to} onChange={(e) => e.target.value && setTo(e.target.value)} />
            <Select aria-label={t('reports.engineerName')} value={engineer} onChange={(e) => setEngineer(e.target.value)}>
              <option value="">{t('reports.allEngineers')}</option>
              {engineers.map((x) => (
                <option key={x} value={x}>
                  {x}
                </option>
              ))}
            </Select>
          </div>
        )}
        <div className={s.spacer} />
        <Button variant="primary" icon={Printer} onClick={print}>
          {t('reports.print')}
        </Button>
      </div>

      <div className={s.layout}>
        <ReportSheet title={t('reports.dailyTitle')} period={period} stamp={stamp}>
          {days.length === 0 ? (
            <p className={s.muted}>{t('reports.noActivityRange')}</p>
          ) : (
            days.map((x) => (
              <DayBlock key={x} day={x} heading={mode === 'range'} notes={notesFor(x)} diaryEntry={diary.days[x]} onDeleteNote={setToDelete} />
            ))
          )}
        </ReportSheet>
        {mode === 'day' && (
          <div className={d.side}>
            <DiaryCard key={`diary-${day}`} day={day} dayLabel={dayTitle(day, lang)} diary={diary} canEdit={allowed('record.work')} onSave={saveDiaryDay} />
            <NoteForm
              key={day}
              day={day}
              engineers={engineers}
              onSave={(note) => {
                setNotes((list) => [note, ...list]);
                toast({ title: t('reports.noteSaved') });
              }}
            />
          </div>
        )}
      </div>

      <ConfirmDialog
        open={toDelete !== null}
        onOpenChange={(open) => !open && setToDelete(null)}
        title={t('reports.deleteNoteTitle')}
        message={toDelete?.details || ''}
        confirmLabel={t('common.delete')}
        tone="danger"
        onConfirm={() => setNotes((list) => list.filter((n) => n.id !== toDelete.id))}
      />
    </Page>
  );
}
