import { useState, useEffect, useMemo, useRef } from 'react';
import { resolveWho } from '../../utils/Registries';
import { ORDER_TYPES, ordersInRange } from '../../utils/OrderEngine';
import { useI18n } from '../../i18n/useI18n.js';
import { formatCurrency } from '../../i18n/index.js';
import './DailyReports.css';

const REPORTS_STORAGE_KEY = 'project-manager-daily-reports';

/* ─────────────────────────────────────────────────────────────
   Work orders recorded this day — auto "work done" body.
   The section builds itself from the order ledger for the
   selected day; the engineer only fills what orders can't
   capture (weather, manpower, equipment, visitors, issues).
   ───────────────────────────────────────────────────────────── */

const EMPTY_REGISTRIES = { contractors: [], teams: [], workers: [] };

const asArray = (value) => (Array.isArray(value) ? value : []);

const numFmt = new Intl.NumberFormat('en-US', { maximumFractionDigits: 2 });
const fmtNum = (v) => numFmt.format(Number.isFinite(Number(v)) ? Number(v) : 0);

// ORDER_TYPES labels localize themselves via the active language;
// `t` only supplies the fallback for unknown type codes.
const orderTypeLabel = (type, t) => ORDER_TYPES[type]?.label || t('reports.orderTypeFallback');

/** Build the display model for ONE day's orders (pure). */
const buildDayOrdersModel = (dayOrders, tasks, registries, t) => {
  const tasksById = new Map(asArray(tasks).map((task) => [task.id, task]));
  const groups = []; // value orders grouped by task (insertion order kept)
  const byTaskKey = new Map();
  const expenses = [];
  let count = 0;
  let totalQty = 0;
  let valuedTotal = 0;
  let expenseTotal = 0;
  let pendingCount = 0;

  asArray(dayOrders).forEach((o) => {
    if (!o || !o.date) return;
    count += 1;
    const pending = o.status !== 'approved';
    if (pending) pendingCount += 1;

    if (o.family === 'value') {
      // Task-less value orders (e.g. soil tests) share one "no task" group
      const key = o.taskId || '__no_task__';
      let group = byTaskKey.get(key);
      if (!group) {
        const task = o.taskId ? tasksById.get(o.taskId) : null;
        const price = Number(task?.unitPrice);
        const wbs = task?.wbs || o.taskWbs || '';
        const name = task?.name || o.taskName || '';
        group = {
          key,
          label: wbs
            ? `${wbs} — ${name || t('reports.unnamedTask')}`
            : name || t('reports.workWithoutTask'),
          unit: task?.unit || o.unit || '',
          unitPrice: Number.isFinite(price) ? price : 0,
          rows: [],
          subtotalQty: 0,
          valuedAmount: 0,
        };
        byTaskKey.set(key, group);
        groups.push(group);
      }
      const q = Number(o.quantity);
      const qty = Number.isFinite(q) ? q : 0;
      group.rows.push({
        id: o.id,
        typeLabel: orderTypeLabel(o.type, t),
        whoLabel: resolveWho(registries, o.who),
        qty,
        unit: o.unit || group.unit,
        pending,
      });
      group.subtotalQty += qty;
      totalQty += qty;
    } else if (o.family === 'expense') {
      const a = Number(o.amount);
      const amount = Number.isFinite(a) ? a : 0;
      expenses.push({
        id: o.id,
        typeLabel: orderTypeLabel(o.type, t),
        whoLabel: resolveWho(registries, o.who),
        amount,
        pending,
      });
      expenseTotal += amount;
    }
  });

  groups.forEach((g) => {
    g.valuedAmount = g.subtotalQty * g.unitPrice; // Σ qty × tasks[taskId].unitPrice
    valuedTotal += g.valuedAmount;
  });

  return {
    groups,
    expenses,
    count,
    totalQty,
    valuedTotal,
    expenseTotal,
    pendingCount,
    isEmpty: groups.length === 0 && expenses.length === 0,
  };
};

/**
 * The auto-generated orders section. Rendered wherever the report
 * content renders: the entry view (for the form's selected date)
 * and the print canvas (one block per day inside the filter range).
 */
const DayOrdersSection = ({ dateLabel, dayOrders, tasks, registries }) => {
  const { t, lang } = useI18n();
  // `t` in the deps rebuilds the model (incl. lazily-localized labels)
  // whenever the active language changes.
  const model = useMemo(
    () => buildDayOrdersModel(dayOrders, tasks, registries, t),
    [dayOrders, tasks, registries, t]
  );

  return (
    <section className="day-orders" aria-label={t('reports.dayOrdersTitle')}>
      <header className="day-orders-head">
        <h3 className="day-orders-title">
          {t('reports.dayOrdersTitle')}
          {dateLabel && <span className="day-orders-date">{dateLabel}</span>}
        </h3>
        <span className="day-orders-auto-tag">{t('reports.autoGenerated')}</span>
      </header>

      {model.isEmpty ? (
        <p className="day-orders-empty">{t('reports.dayOrdersEmpty')}</p>
      ) : (
        <>
          <div className="day-orders-strip">
            <div className="kpi-compact-card">
              <span className="kpi-compact-label">{t('reports.orderCount')}</span>
              <span className="kpi-compact-value">{model.count}</span>
            </div>
            <div className="kpi-compact-card">
              <span className="kpi-compact-label">{t('reports.chipTotalQty')}</span>
              <span className="kpi-compact-value">{fmtNum(model.totalQty)}</span>
            </div>
            <div className="kpi-compact-card">
              <span className="kpi-compact-label">{t('reports.valuedAmount')}</span>
              <span className="kpi-compact-value">{formatCurrency(model.valuedTotal, lang)}</span>
            </div>
            <div className="kpi-compact-card">
              <span className="kpi-compact-label">{t('reports.totalExpenses')}</span>
              <span className="kpi-compact-value">{formatCurrency(model.expenseTotal, lang)}</span>
            </div>
            {model.pendingCount > 0 && (
              <div className="kpi-compact-card warning">
                <span className="kpi-compact-label">{t('common.pending')}</span>
                <span className="kpi-compact-value">{model.pendingCount}</span>
              </div>
            )}
          </div>

          {model.groups.length > 0 && (
            <div className="day-orders-value">
              <h4>{t('reports.valueOrdersTitle')}</h4>
              {model.groups.map((g) => (
                <div key={g.key} className="day-orders-task">
                  <div className="day-orders-task-head">
                    <strong>{g.label}</strong>
                    <span className="day-orders-task-sub">
                      {t('common.total')}: {fmtNum(g.subtotalQty)} {g.unit}
                      {g.unitPrice > 0 && (
                        <> — {t('reports.valuedAmount')}: {formatCurrency(g.valuedAmount, lang)}</>
                      )}
                    </span>
                  </div>
                  <ul className="day-orders-rows">
                    {g.rows.map((r) => (
                      <li key={r.id} className="dor-row">
                        <span className="dor-who">
                          {r.whoLabel !== '—' ? r.whoLabel : r.typeLabel}
                        </span>
                        {r.whoLabel !== '—' && <span className="dor-type">{r.typeLabel}</span>}
                        <span className="dor-qty">
                          {fmtNum(r.qty)} {r.unit}
                        </span>
                        {r.pending && <span className="dor-badge">{t('common.pending')}</span>}
                      </li>
                    ))}
                  </ul>
                </div>
              ))}
            </div>
          )}

          {model.expenses.length > 0 && (
            <div className="day-orders-expenses">
              <h4>{t('reports.recordedExpenses')}</h4>
              <table className="reports-table day-orders-table">
                <thead>
                  <tr>
                    <th>{t('common.type')}</th>
                    <th>{t('reports.colParty')}</th>
                    <th>{t('reports.colAmountIqd')}</th>
                    <th>{t('common.status')}</th>
                  </tr>
                </thead>
                <tbody>
                  {model.expenses.map((e) => (
                    <tr key={e.id}>
                      <td>{e.typeLabel}</td>
                      <td>{e.whoLabel}</td>
                      <td className="dor-amount">{fmtNum(e.amount)}</td>
                      <td>
                        {e.pending ? (
                          <span className="dor-badge">{t('common.pending')}</span>
                        ) : (
                          <span className="dor-approved">{t('common.approved')}</span>
                        )}
                      </td>
                    </tr>
                  ))}
                </tbody>
                <tfoot>
                  <tr>
                    <td colSpan={2}>{t('reports.totalExpenses')}</td>
                    <td className="dor-amount">{fmtNum(model.expenseTotal)}</td>
                    <td></td>
                  </tr>
                </tfoot>
              </table>
            </div>
          )}
        </>
      )}
    </section>
  );
};

const DailyReports = ({ tasks = [], orders = [], registries, identity }) => {
  const { t, dir } = useI18n();
  const whoRegistries = registries || EMPTY_REGISTRIES;
  const [reports, setReports] = useState(() => {
    try {
      const saved = localStorage.getItem(REPORTS_STORAGE_KEY);
      return saved ? JSON.parse(saved) : [];
    } catch {
      return [];
    }
  });

  const [activeTab, setActiveTab] = useState('entry'); // 'entry' or 'report'

  // Form State
  const [date, setDate] = useState(() => new Date().toISOString().split('T')[0]);
  const [engineer, setEngineer] = useState('');
  const [taskId, setTaskId] = useState('');
  const [details, setDetails] = useState('');
  const [quantity, setQuantity] = useState('');

  // Filter State
  const [filterFrom, setFilterFrom] = useState('');
  const [filterTo, setFilterTo] = useState('');
  const [filterEngineer, setFilterEngineer] = useState('all');
  const [filterTask, setFilterTask] = useState('all');

  useEffect(() => {
    localStorage.setItem(REPORTS_STORAGE_KEY, JSON.stringify(reports));
  }, [reports]);

  // "Enter once": prefill the engineer field from the signed-in identity
  // (only while it is still empty, so manual edits are never overwritten).
  const identityPrefilled = useRef(false);
  useEffect(() => {
    if (identityPrefilled.current || !identity?.name) return;
    identityPrefilled.current = true;
    setEngineer((prev) => prev || identity.name);
  }, [identity]);

  // Derived unique engineers from past reports for dropdowns
  const uniqueEngineers = useMemo(() => {
    const engs = new Set(reports.map(r => r.engineer).filter(Boolean));
    return Array.from(engs).sort();
  }, [reports]);

  // Only leaf tasks (subtasks) should get progress logged
  const subTasks = useMemo(() => {
    return tasks.filter(t => !t.isGroup);
  }, [tasks]);

  const handleSaveReport = (e) => {
    e.preventDefault();
    if (!date || !engineer || !taskId) return alert(t('reports.validationRequired'));

    const taskObj = tasks.find(task => task.id === taskId);
    const newReport = {
      id: 'rep_' + Date.now(),
      date,
      engineer,
      taskId,
      taskName: taskObj ? taskObj.name : t('reports.unknownTask'),
      taskWbs: taskObj ? taskObj.wbs : '',
      details,
      quantity: quantity ? parseFloat(quantity) : 0,
      timestamp: Date.now()
    };

    setReports([newReport, ...reports]);
    // Reset fields except date and engineer for faster subsequent entries
    setTaskId('');
    setDetails('');
    setQuantity('');
    alert(t('reports.savedOk'));
  };

  const handleDelete = (id) => {
    if (window.confirm(t('reports.deleteConfirm'))) {
      setReports(reports.filter(r => r.id !== id));
    }
  };

  const filteredReports = useMemo(() => {
    return reports.filter(r => {
      // Date filter
      if (filterFrom && r.date < filterFrom) return false;
      if (filterTo && r.date > filterTo) return false;

      // Engineer filter
      if (filterEngineer !== 'all' && r.engineer !== filterEngineer) return false;

      // Task filter
      if (filterTask !== 'all' && r.taskId !== filterTask) return false;

      return true;
    }).sort((a, b) => new Date(b.date) - new Date(a.date)); // Sort newest first
  }, [reports, filterFrom, filterTo, filterEngineer, filterTask]);

  const totalFilteredQuantity = useMemo(() => {
    return filteredReports.reduce((sum, r) => sum + (r.quantity || 0), 0);
  }, [filteredReports]);

  // Orders booked on the entry form's selected date → the auto work-done body
  const entryDayOrders = useMemo(
    () => asArray(orders).filter((o) => o && o.date === date),
    [orders, date]
  );

  // Orders inside the print view's date range, grouped per day (newest first)
  const printOrderDays = useMemo(() => {
    const byDay = new Map();
    ordersInRange(asArray(orders), filterFrom, filterTo).forEach((o) => {
      if (!o || !o.date) return;
      if (!byDay.has(o.date)) byDay.set(o.date, []);
      byDay.get(o.date).push(o);
    });
    return Array.from(byDay.entries())
      .sort((a, b) => b[0].localeCompare(a[0]))
      .map(([day, list]) => ({ day, list }));
  }, [orders, filterFrom, filterTo]);

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="reports-container" dir={dir}>

      {/* Tab Navigation (Hidden during print) */}
      <div className="reports-header no-print">
        <h2 style={{margin: 0}}>{t('reports.title')}</h2>
        <div className="reports-tabs">
          <button
            className={`reports-tab ${activeTab === 'entry' ? 'active' : ''}`}
            onClick={() => setActiveTab('entry')}
          >
            {t('reports.tabEntry')}
          </button>
          <button
            className={`reports-tab ${activeTab === 'report' ? 'active' : ''}`}
            onClick={() => setActiveTab('report')}
          >
            {t('reports.tabPrint')}
          </button>
        </div>
      </div>

      {activeTab === 'entry' && (
        <div className="reports-entry-view no-print">
          <form className="reports-form" onSubmit={handleSaveReport}>
            <h3>{t('reports.addRecord')}</h3>

            <div className="form-grid">
              <div className="form-group">
                <label>{t('common.date')}</label>
                <input type="date" value={date} onChange={e => setDate(e.target.value)} required />
              </div>

              <div className="form-group">
                <label>{t('reports.engineerName')}</label>
                <input
                  type="text"
                  value={engineer}
                  onChange={e => setEngineer(e.target.value)}
                  list="engineers-list"
                  placeholder={t('reports.engineerPh')}
                  required
                />
                <datalist id="engineers-list">
                  {uniqueEngineers.map(eng => <option key={eng} value={eng} />)}
                </datalist>
              </div>
            </div>

            <div className="form-group">
              <label>{t('reports.taskItem')}</label>
              <select value={taskId} onChange={e => setTaskId(e.target.value)} required>
                <option value="">{t('reports.selectTask')}</option>
                {subTasks.map(task => (
                  <option key={task.id} value={task.id}>
                    {task.wbs} - {task.name.substring(0, 80)}{task.name.length > 80 ? '...' : ''}
                  </option>
                ))}
              </select>
            </div>

            <div className="form-grid">
              <div className="form-group">
                <label>{t('reports.executedQtyOptional')}</label>
                <input type="number" step="any" value={quantity} onChange={e => setQuantity(e.target.value)} placeholder={t('reports.qtyExample')} />
              </div>
            </div>

            <div className="form-group">
              <label>{t('reports.detailsNotes')}</label>
              <textarea
                value={details}
                onChange={e => setDetails(e.target.value)}
                rows={4}
                placeholder={t('reports.detailsPlaceholder')}
              ></textarea>
            </div>

            <div className="form-actions">
              <button type="submit" className="apple-btn primary">{t('reports.saveRecord')}</button>
            </div>
          </form>

          {/* Auto "work done" body for the selected date (follows the form's date) */}
          <div className="recent-logs">
            <DayOrdersSection
              dateLabel={date}
              dayOrders={entryDayOrders}
              tasks={tasks}
              registries={whoRegistries}
            />

            <h3>{t('reports.recentRecords')}</h3>
            <div className="reports-table-wrapper">
              <table className="reports-table">
                <thead>
                  <tr>
                    <th>{t('common.date')}</th>
                    <th>{t('reports.colEngineer')}</th>
                    <th>{t('reports.colTask')}</th>
                    <th>{t('common.quantity')}</th>
                    <th>{t('common.actions')}</th>
                  </tr>
                </thead>
                <tbody>
                  {reports.slice(0, 5).map(r => (
                    <tr key={r.id}>
                      <td>{r.date}</td>
                      <td>{r.engineer}</td>
                      <td title={r.taskName}>{r.taskWbs} - {r.taskName.substring(0,30)}</td>
                      <td>{r.quantity}</td>
                      <td>
                        <button type="button" onClick={() => handleDelete(r.id)} className="apple-btn destructive" style={{padding: '4px 8px', fontSize: '0.75rem'}}>{t('common.delete')}</button>
                      </td>
                    </tr>
                  ))}
                  {reports.length === 0 && (
                    <tr>
                      <td colSpan="5" style={{textAlign: 'center', padding: '24px', color: 'var(--text-muted)'}}>{t('reports.noRecords')}</td>
                    </tr>
                  )}
                </tbody>
              </table>
            </div>
          </div>
        </div>
      )}

      {activeTab === 'report' && (
        <div className="reports-print-view">

          <div className="reports-filters no-print">
            <div className="filter-group">
              <label>{t('reports.fromDate')}</label>
              <input type="date" value={filterFrom} onChange={e => setFilterFrom(e.target.value)} />
            </div>
            <div className="filter-group">
              <label>{t('reports.toDate')}</label>
              <input type="date" value={filterTo} onChange={e => setFilterTo(e.target.value)} />
            </div>
            <div className="filter-group">
              <label>{t('reports.engineerName')}</label>
              <select value={filterEngineer} onChange={e => setFilterEngineer(e.target.value)}>
                <option value="all">{t('reports.all')}</option>
                {uniqueEngineers.map(eng => <option key={eng} value={eng}>{eng}</option>)}
              </select>
            </div>
            <div className="filter-group">
              <label>{t('reports.colTask')}</label>
              <select value={filterTask} onChange={e => setFilterTask(e.target.value)}>
                <option value="all">{t('reports.all')}</option>
                {subTasks.map(task => <option key={task.id} value={task.id}>{task.wbs} - {task.name.substring(0, 50)}</option>)}
              </select>
            </div>
            <div className="filter-actions">
              <button onClick={handlePrint} className="apple-btn primary">{t('reports.printReport')}</button>
            </div>
          </div>

          <div className="print-canvas">
            <div className="print-header">
              <h2>{t('reports.printTitle')}</h2>
              <div className="print-meta">
                {filterFrom && <span><strong>{t('reports.fromColon')}</strong> {filterFrom}</span>}
                {filterTo && <span><strong>{t('reports.toColon')}</strong> {filterTo}</span>}
                {filterEngineer !== 'all' && <span><strong>{t('reports.engineerColon')}</strong> {filterEngineer}</span>}
                {filterTask !== 'all' && <span>{t('reports.taskFiltered')}</span>}
              </div>
            </div>

            <table className="reports-table">
              <thead>
                <tr>
                  <th>{t('common.date')}</th>
                  <th>{t('reports.engineerName')}</th>
                  <th>{t('reports.colTask')}</th>
                  <th>{t('reports.colDetails')}</th>
                  <th>{t('common.quantity')}</th>
                </tr>
              </thead>
              <tbody>
                {filteredReports.map(r => (
                  <tr key={r.id}>
                    <td width="10%">{r.date}</td>
                    <td width="15%">{r.engineer}</td>
                    <td width="30%"><strong>{r.taskWbs}</strong> - {r.taskName}</td>
                    <td width="35%">{r.details}</td>
                    <td width="10%">{r.quantity}</td>
                  </tr>
                ))}
                {filteredReports.length === 0 && (
                  <tr>
                    <td colSpan="5" style={{textAlign: 'center', padding: '40px', color: '#888'}}>{t('reports.noMatching')}</td>
                  </tr>
                )}
              </tbody>
              {filteredReports.length > 0 && (
                <tfoot>
                  <tr>
                    <td colSpan="4" style={{textAlign: 'end', fontWeight: 'bold'}}>{t('reports.totalExecutedQty')}</td>
                    <td style={{fontWeight: 'bold', color: 'var(--apple-blue-action)'}}>{totalFilteredQuantity}</td>
                  </tr>
                </tfoot>
              )}
            </table>

            {/* Auto "work done" body — one block per day inside the filter range */}
            <div className="print-orders">
              {printOrderDays.length === 0 ? (
                <DayOrdersSection dayOrders={[]} tasks={tasks} registries={whoRegistries} />
              ) : (
                printOrderDays.map(({ day, list }) => (
                  <DayOrdersSection
                    key={day}
                    dateLabel={day}
                    dayOrders={list}
                    tasks={tasks}
                    registries={whoRegistries}
                  />
                ))
              )}
            </div>
          </div>

        </div>
      )}

    </div>
  );
};

export default DailyReports;
