export const LEGACY_SEED_TEMPLATES = [schoolTemplate, apartmentsTemplate, mallTemplate, houseTemplate, villaTemplate];

/** True for a schema-2 (auto-planning) template. */
export const isPlanTemplate = (template) => Number(template?.schema) === 2;

/** Templates shown in lists (archived ones hidden). */
export const activeTemplates = (templates) => (templates || []).filter((t) => t && !t.archived);

/* ═══════════════════════════════════════════════════════════════════
   Storage API
   ═══════════════════════════════════════════════════════════════════ */
const readStore = () => {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    return raw ? JSON.parse(raw) : null;
  } catch {
    return null;
  }
};

const writeStore = (templates) => {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify({ templates, seedVersion: TEMPLATE_SEED_VERSION }));
  } catch {
    /* ignore write failures */
  }
};

/** Every stored template (archived included — see activeTemplates). */
export const listTemplates = () => {
  const store = readStore();
  if (store && Array.isArray(store.templates)) {
    if ((Number(store.seedVersion) || 1) >= TEMPLATE_SEED_VERSION) return store.templates;
    // Seed version 1 store: archive its schema-1 seeds, add the building templates.
    const upgraded = [
      ...store.templates.map((t) => (t && t.source === 'seed' && !isPlanTemplate(t) ? { ...t, archived: true } : t)),
      ...buildingTemplateSeeds(),
    ];
    writeStore(upgraded);
    return upgraded;
  }
  const seeded = buildingTemplateSeeds();
  writeStore(seeded);
  return seeded;
};

export const saveTemplate = (template) => {
  const clean = {
    ...template,
    id: template.id || uid(),
    name: template.name || 'نموذج بدون اسم',
    icon: template.icon || '🏗️',
    variables: Array.isArray(template.variables) ? template.variables : [],
    elements: Array.isArray(template.elements) ? template.elements : [],
    version: template.version || 1,
    createdAt: template.createdAt || new Date().toISOString(),
  };
  const existing = listTemplates();
  const idx = existing.findIndex((t) => t.id === clean.id);
  const next =
    idx >= 0
      ? existing.map((t) => (t.id === clean.id ? clean : t))
      : [...existing, clean];
  writeStore(next);
  return clean;
};

export const deleteTemplate = (id) => {
  const next = listTemplates().filter((t) => t.id !== id);
  writeStore(next);
  return next;
};
